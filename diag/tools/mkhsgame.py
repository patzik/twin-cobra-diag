#!/usr/bin/env python3
"""Make src/hsgame.inc for the HIGH SCORE (GAME CODE) page: the game's state
captured in MAME at the moment it enters its frame wait ($23E90) at the start
of the attract-mode high score table: work RAM $30000-$31FFF, CPU registers,
all colours, text / FG / BG (both banks) / sprite RAM, latch and spare scroll.
Also the ROM check table entries of program ROMs 8J / 8H of set twincobr, so
the page can make sure the board's 8J / 8H are that version.
Usage: mkhsgame.py capture_dir prog.bin out.inc"""
import sys, os, struct

cap, prog, out = sys.argv[1:4]
def words(name):
    d = open(os.path.join(cap, name), "rb").read()
    return [d[i] << 8 | d[i + 1] for i in range(0, len(d), 2)]
st = {}
for ln in open(os.path.join(cap, "hs5_state.txt")):
    k, v = ln.split()
    st[k] = v
assert st["PC"] == "00023E90" and st["STATE"] == "0002" and st["STACKTOP"] == "00020250"
p = open(prog, "rb").read()
t1, t3 = struct.unpack(">I", p[0x2FFEC:0x2FFF0])[0], struct.unpack(">I", p[0x2FFF4:0x2FFF8])[0]

o = ["/* generated by tools/mkhsgame.py from a MAME capture of the game -",
     " * game data, keep the repo private */",
     "    .equ HG_PC,   0x%s" % st["PC"], "    .equ HG_SR,   0x%s" % st["SR"][4:],
     "    .equ HG_SP,   0x%s" % st["SP"],
     "    .equ HG_SUM1, 0x%08x                 /* 8J/8H ROM check table, even lane */" % t1,
     "    .equ HG_SUM3, 0x%08x                 /* odd lane */" % t3,
     "    .equ HG_Q4,   %s" % st["Q4"], "    .equ HG_Q5,   %s" % st["Q5"], "    .equ HG_Q3,   %s" % st["Q3"],
     "    .equ HG_EX0,  0x%s" % st["EX0"], "    .equ HG_EX1,  0x%s" % st["EX1"],
     "    .even", "hg_regs:                              /* D0-D7, A0-A6 */"]
o.append("    .long " + ",".join("0x" + st[r] for r in ("D0","D1","D2","D3","D4","D5","D6","D7")))
o.append("    .long " + ",".join("0x" + st[r] for r in ("A0","A1","A2","A3","A4","A5","A6")))
def table(label, ws, note):
    o.append("%s:  /* %s */" % (label, note))
    for i in range(0, len(ws), 8):
        o.append("    .word " + ",".join("0x%04x" % w for w in ws[i:i + 8]))
table("hg_ram", words("hs5_ram.bin"), "work RAM $30000-$31FFF")
table("hg_pal", words("hs5_pal.bin"), "all 1792 colours")
table("hg_tx", words("hs5_tx.bin"), "text RAM")
table("hg_fg", words("hs5_fg.bin"), "FG RAM")
table("hg_bg", words("hs5_bg.bin"), "BG RAM, bank 0 then bank 1")
table("hg_spr", words("hs5_spr.bin"), "sprite RAM")
open(out, "w").write("\n".join(o) + "\n")
print("ok", st["PC"], st["SP"], hex(t1), hex(t3))
