#!/usr/bin/env python3
"""Make src/hsdata.inc for the high score replay page from a MAME capture of
the game's attract-mode high score scroll (text RAM and palette at the frame
before it starts, then every text-layer register write with its time in the
frame). Usage: mkhs.py writes.txt tx.bin pal.bin out.inc"""
import sys

CYC = 446 * 286          # 68000 cycles per frame (7 MHz = the pixel clock)
VBEND = 0.161            # VBLANK ends this far into the frame (as captured)
OVH = 60                 # cycles the replay loop itself spends per pair
LOOP = 10                # cycles per dbra delay iteration

wlog, txf, palf, out = sys.argv[1:5]
frames = {}
for ln in open(wlog):
    f = ln.split()
    if f[2] == "VBL":
        continue
    n, t, reg, v = int(f[0]), float(f[1]), f[2], int(f[3], 16)
    fr = frames.setdefault(n, {"sx": None, "sy": None, "pairs": []})
    if reg == "70000":
        fr["sx"] = v
    elif reg == "70002":
        fr["sy"] = v
    elif reg in ("70004", "70006"):
        fr["pairs"].append([t, v, None])
    elif reg == "7E000":
        fr["pairs"][-1][2] = v
tx = open(txf, "rb").read()
pal = open(palf, "rb").read()

o = ["/* generated by tools/mkhs.py from a MAME capture of the game's high",
     " * score scroll - game data, keep the repo private */", "    .even", "hs_tx:"]
for i in range(0, 4096, 16):
    o.append("    .word " + ",".join("0x%04x" % (tx[j] << 8 | tx[j + 1]) for j in range(i, i + 16, 2)))
o.append("hs_pal:                               /* text colour sets 0-31 */")
for i in range(1536 * 2, 1792 * 2, 16):
    o.append("    .word " + ",".join("0x%04x" % (pal[j] << 8 | pal[j + 1]) for j in range(i, i + 16, 2)))
o.append("/* per frame: x scroll, y scroll, pair count, then per pair: delay")
o.append(" * (dbra loops, -1 = none), offset, data */")
o.append("hs_frames:")
keys = sorted(frames)
npairs = 0
for n in keys:
    fr = frames[n]
    ps = [p for p in fr["pairs"] if p[2] is not None]
    o.append("    .word 0x%04x,0x%04x,%d" % (fr["sx"], fr["sy"], len(ps)))
    prev = VBEND
    for t, off, d in ps:
        cyc = (t - prev) * CYC - OVH
        prev = t
        loops = int(cyc / LOOP) - 1 if cyc > LOOP else -1
        o.append("    .word %d,0x%04x,0x%04x" % (min(loops, 32767), off, d))
        npairs += 1
o.append("    .equ HS_NF, %d" % len(keys))
open(out, "w").write("\n".join(o) + "\n")
print(len(keys), "frames,", npairs, "pairs")
