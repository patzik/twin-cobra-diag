#!/usr/bin/env python3
"""Make src/hsdata.inc for the high score replay page from a MAME capture of
the game's attract-mode high score scroll: the game's whole video state at the
frame before the scroll starts (palette, text / FG / BG RAM, sprite RAM), then
every video write it makes, with its time in the frame.
Usage: mkhs.py capture_dir out.inc   (capture_dir holds hs4_*.bin, hs4_ops.txt)"""
import sys, os

CYC = 446 * 286          # 68000 cycles per frame (7 MHz = the pixel clock)
VBEND = 0.161            # VBLANK ends this far into the frame (as captured)
OVH = 50                 # cycles the replay loop itself spends per write
LOOP = 10                # cycles per dbra delay iteration
REPLAY = [(0x050000, 0x050dff), (0x070000, 0x070007), (0x072000, 0x072007),
          (0x074000, 0x074007), (0x07e000, 0x07e005)]

cap, out = sys.argv[1:3]
def words(name):
    d = open(os.path.join(cap, name), "rb").read()
    return [d[i] << 8 | d[i + 1] for i in range(0, len(d), 2)]

frames = {}
for ln in open(os.path.join(cap, "hs4_ops.txt")):
    n, t, a, v = ln.split()
    n, t, a, v = int(n), float(t), int(a, 16), int(v, 16)
    if not any(lo <= a <= hi for lo, hi in REPLAY):
        continue          # latch (IRQ enable, DSP kick), shared RAM: left out
    fr = frames.setdefault(n, ([], []))
    (fr[0] if t < VBEND else fr[1]).append((t, a, v))

o = ["/* generated by tools/mkhs.py from a MAME capture of the game's high",
     " * score scroll - game data, keep the repo private */", "    .even"]
def table(label, ws, note):
    o.append("%s:%s" % (label, ("  /* " + note + " */") if note else ""))
    for i in range(0, len(ws), 8):
        o.append("    .word " + ",".join("0x%04x" % w for w in ws[i:i + 8]))
table("hs_pal", words("hs4_pal.bin"), "all 1792 colours")
table("hs_tx", words("hs4_tx.bin"), "text RAM")
table("hs_fg", words("hs4_fg.bin"), "FG RAM")
table("hs_bg", words("hs4_bg.bin")[:4096], "BG RAM bank 0 (the bank in use)")
table("hs_spr", words("hs4_spr.bin"), "sprite RAM")
o.append("/* per frame: count of VBLANK writes, count of picture writes, then")
o.append(" * each write: delay (dbra loops, -1 = none), address, data */")
o.append("hs_frames:")
nops = 0
for n in sorted(frames):
    vb, pic = frames[n]
    o.append("    .word %d,%d" % (len(vb), len(pic)))
    for t, a, v in vb:
        o.append("    .word -1\n    .long 0x%06x\n    .word 0x%04x" % (a, v))
    prev = VBEND
    for t, a, v in pic:
        cyc = (t - prev) * CYC - OVH
        prev = t
        loops = int(cyc / LOOP) - 1 if cyc > LOOP else -1
        o.append("    .word %d\n    .long 0x%06x\n    .word 0x%04x" % (min(loops, 32767), a, v))
    nops += len(vb) + len(pic)
o.append("    .equ HS_NF, %d" % len(frames))
open(out, "w").write("\n".join(o) + "\n")
print(len(frames), "frames,", nops, "writes")
